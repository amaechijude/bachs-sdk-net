/// <summary>
/// Converts Bachs API error codes to enum values while preserving error deserialization
/// when the API introduces a code that is not yet known to this SDK.
/// </summary>
public sealed class BachsErrorCodeJsonConverter : JsonConverter<BachsErrorCode>
{
    /// <inheritdoc />
    public override BachsErrorCode Read(
        ref Utf8JsonReader reader,
        Type typeToConvert,
        JsonSerializerOptions options
    )
    {
        if (reader.TokenType != JsonTokenType.String)
            throw new JsonException("An error code must be a JSON string.");

        var value = reader.GetString();
        return
            Enum.TryParse(value, ignoreCase: true, out BachsErrorCode errorCode)
            && Enum.IsDefined(errorCode)
            ? errorCode
            : BachsErrorCode.UNKNOWN;
    }

    /// <inheritdoc />
    public override void Write(
        Utf8JsonWriter writer,
        BachsErrorCode value,
        JsonSerializerOptions options
    ) =>
        writer.WriteStringValue(
            Enum.IsDefined(value) ? value.ToString() : nameof(BachsErrorCode.UNKNOWN)
        );
}
